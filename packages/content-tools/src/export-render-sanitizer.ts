import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync, gzipSync } from "node:zlib";
import MarkdownIt from "markdown-it";
import matter from "gray-matter";
import { normalizeMarkdownBody } from "./content/generator-core.js";
import { readString } from "./content/build-site-content.js";
import { sanitizeArticleHtml } from "./content/render-sanitizer.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const destination = path.join(root, "services/api/internal/render");
// Use the same jsdom dependency as the original sanitizer to discover its DOM names.
const require = createRequire(import.meta.resolve("isomorphic-dompurify"));
const { JSDOM } = require("jsdom");
const window = new JSDOM("").window;
const names = new Set<string>();
for (let value of [window.document, window.document.createElement("form")]) {
  while (value) { Object.getOwnPropertyNames(value).forEach(name => names.add(name)); value = Object.getPrototypeOf(value); }
}
window.close();
const clobbered = [...names].filter(name => !sanitizeArticleHtml(`<div id="${name.replaceAll('"', "&quot;")}"></div>`).includes(" id=")).sort();
const table = `// Code generated by export-render-sanitizer.ts from the original DOMPurify policy; DO NOT EDIT.\npackage render\n\nvar clobberedArticleIDs = map[string]bool{\n${clobbered.map(name => `\t${JSON.stringify(name)}: true,`).join("\n")}\n}\n`;
const formatted = execFileSync("gofmt", [], { input: table, encoding: "utf8" });
const tablePath = path.join(destination, "sanitizer_ids.gen.go");
if (process.argv.includes("--check")) {
  if (await readFile(tablePath, "utf8") !== formatted) throw new Error("Sanitizer DOM-name table drift");
} else await writeFile(tablePath, formatted);

const cases: { name: string; raw: string; expected: string }[] = [];
function add(name: string, raw: string) { cases.push({ name, raw, expected: sanitizeArticleHtml(raw) }); }
for (const [name, raw] of Object.entries({
  scripts: '<p>before<script>alert(1)</script><style>body{}</style>after</p>',
  attributes: '<p id="ok" class="x" style="color:red" onclick="evil()" data-x="a" aria-label=" test " aria-foo="x" role="note">text</p>',
  links: '<a href="javascript:alert(1)" target="_blank">bad</a><a href="https://x.test/a b" rel="tag">space</a><a href="#part">part</a>',
  protocols: '<a href="java&#10;script:alert(1)">bad</a><a href="data:text/html,x">data</a><a href="mailto:x@y.test">mail</a><a href="tel:123">tel</a><a href="matrix:a">matrix</a>',
  images: '<img src="data:image/svg+xml;base64,PHN2Zz4=" onerror="alert(1)" alt="img" loading="lazy" decoding="async" width="100" height="20">',
  emptyURLs: '<a href="">empty</a><img src=""><div href="javascript:x" src="https://x.test" width="javascript:x">x</div>',
  forbidden: '<svg><text>svg</text></svg><math><mi>x</mi></math><template><p>template</p></template><iframe>frame</iframe><object>object</object><nostyle>nostyle</nostyle>',
  unknown: '<custom-tag>keep <strong>bold</strong></custom-tag><form>form <input value="x"></form><textarea>literal &lt;b&gt;</textarea>',
  table: '<table><tr><td colspan="2">cell</td></tr></table><details open><summary>title</summary>body</details>',
  broken: '<p>one<div>two</p>three</div><!-- comment -->',
  names: '<h2 id="location">a</h2><p id="__proto__">b</p><p id="constructor">c</p><p id="normal-id">d</p>',
  escapes: '<p title="  a &amp; b  ">a &lt; b &amp; &quot;quoted&quot; &#39;x&#39;</p>',
})) add(`edge/${name}`, raw);
const files = execFileSync("git", ["ls-files", "-z", "--", "apps/blog/content/source/myblog"], { cwd: root, encoding: "utf8" }).split("\0").filter(file => file.endsWith(".md")).sort();
const md = new MarkdownIt({ html: true, linkify: true, breaks: false });
for (const file of files) {
  const raw = await readFile(path.join(root, file), "utf8");
  const title = readString(matter(raw).data.title) || path.basename(file, ".md");
  add(file, md.render(normalizeMarkdownBody(raw, title)));
}
const oracle = path.join(destination, "testdata/sanitizer.json.gz");
const serialized = JSON.stringify(cases);
if (process.argv.includes("--check")) {
  if (gunzipSync(await readFile(oracle)).toString("utf8") !== serialized) throw new Error("Sanitizer oracle drift");
} else {
  await mkdir(path.dirname(oracle), { recursive: true });
  await writeFile(oracle, gzipSync(serialized, { level: 9 }));
}
console.log(JSON.stringify({ articles: files.length, edgeCases: cases.length - files.length, blockedIDs: clobbered.length }));
